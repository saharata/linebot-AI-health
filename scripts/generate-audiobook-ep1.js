const OUTPUT_DIR = path.join(__dirname, "..", "voiceover-ep1");
if (!fs.existsSync(OUTPUT_DIR)) fs.mkdirSync(OUTPUT_DIR, { recursive: true });

async function generate(chapter) {
  const url = `https://api.elevenlabs.io/v1/text-to-speech/${VOICE_LIAM}?output_format=mp3_44100_128`;
  const res = await fetch(url, {
    method: "POST",
    headers: {
      "xi-api-key": API_KEY,
      "Content-Type": "application/json",
      Accept: "audio/mpeg"
    },
    body: JSON.stringify({
      text: chapter.text,
      model_id: MODEL,
      voice_settings: SETTINGS
    })
  });
  if (!res.ok) {
    const err = await res.text();
    throw new Error(`${res.status} ${err}`);
  }
  const buffer = await res.buffer();
  const outPath = path.join(OUTPUT_DIR, `${chapter.id}.mp3`);
  fs.writeFileSync(outPath, buffer);
  return outPath;
}

(async () => {
  console.log(`Generating ${CHAPTERS.length} audiobook segments to ${OUTPUT_DIR}\n`);
  for (const chapter of CHAPTERS) {
    process.stdout.write(`  ${chapter.id}... `);
    try {
      const outPath = await generate(chapter);
      const sizeKB = (fs.statSync(outPath).size / 1024).toFixed(0);
      console.log(`✓ ${sizeKB} KB`);
    } catch (err) {
      console.log(`✗ ${err.message}`);
    }
  }
  console.log(`\nDone. Files in ${OUTPUT_DIR}/`);
  console.log("Drag into CapCut in this order: ep1_open → ep1_ch1 → ep1_ch2 → ep1_ch3 → ep1_outro");
})();
