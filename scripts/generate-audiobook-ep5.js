const OUTPUT_DIR = path.join(__dirname, "..", "voiceover-ep5");
if (!fs.existsSync(OUTPUT_DIR)) fs.mkdirSync(OUTPUT_DIR, { recursive: true });

async function generate(ch) {
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_LIAM}?output_format=mp3_44100_128`, {
    method: "POST",
    headers: { "xi-api-key": API_KEY, "Content-Type": "application/json", Accept: "audio/mpeg" },
    body: JSON.stringify({ text: ch.text, model_id: MODEL, voice_settings: SETTINGS })
  });
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  fs.writeFileSync(path.join(OUTPUT_DIR, `${ch.id}.mp3`), await res.buffer());
}

(async () => {
  console.log(`Generating ${CHAPTERS.length} EP5 audio segments\n`);
  for (const c of CHAPTERS) {
    process.stdout.write(`  ${c.id}... `);
    try { await generate(c); console.log("✓"); }
    catch (e) { console.log(`✗ ${e.message}`); }
  }
})();
