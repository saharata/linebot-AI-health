const OUTPUT_DIR = path.join(__dirname, "..", "voiceover-ep2");
if (!fs.existsSync(OUTPUT_DIR)) fs.mkdirSync(OUTPUT_DIR, { recursive: true });

async function generate(chapter) {
  const url = `https://api.elevenlabs.io/v1/text-to-speech/${VOICE_LIAM}?output_format=mp3_44100_128`;
  const res = await fetch(url, {
    method: "POST",
    headers: { "xi-api-key": API_KEY, "Content-Type": "application/json", Accept: "audio/mpeg" },
    body: JSON.stringify({ text: chapter.text, model_id: MODEL, voice_settings: SETTINGS })
  });
  if (!res.ok) throw new Error(`${res.status} ${await res.text()}`);
  const buffer = await res.buffer();
  const outPath = path.join(OUTPUT_DIR, `${chapter.id}.mp3`);
  fs.writeFileSync(outPath, buffer);
  return outPath;
}

(async () => {
  console.log(`Generating ${CHAPTERS.length} audiobook segments to ${OUTPUT_DIR}\n`);
  for (const ch of CHAPTERS) {
    process.stdout.write(`  ${ch.id}... `);
    try {
      await generate(ch);
      const sizeKB = (fs.statSync(path.join(OUTPUT_DIR, `${ch.id}.mp3`)).size / 1024).toFixed(0);
      console.log(`✓ ${sizeKB} KB`);
    } catch (err) { console.log(`✗ ${err.message}`); }
  }
  console.log(`\nDone. Files in ${OUTPUT_DIR}/`);
})();
